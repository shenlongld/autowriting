def scrub_orphan_notes(path: Path):
    tmp = path.with_suffix(".tmp.docx")
    with zipfile.ZipFile(path, "r") as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename in {"word/footnotes.xml", "word/endnotes.xml"}:
                text = data.decode("utf-8", errors="ignore")
                text = re.sub(r"https?://[^<]+", "旧模板链接已删除", text)
                data = text.encode("utf-8")
            zout.writestr(item, data)
    tmp.replace(path)


def validate_text(path: Path):
    doc = Document(path)
    texts = [p.text for p in doc.paragraphs]
    full = "\n".join(texts)
    bad = [word for word in BANNED if word in full]
    pair_bad = bool(re.search(r"不是[^。\n]{0,80}而是", full))
    if bad or pair_bad:
        raise SystemExit(f"Forbidden wording found: {bad}, pair={pair_bad}")
    # lowest-level sections are bounded by numeric subsection headings.
    chunks = []
    current = []
    for t in texts:
        if t.startswith("六、"):
            break
        if re.match(r"^\d+\.\d+\s", t):
            if current:
                chunks.append("".join(current))
            current = [t]
        elif current:
            current.append(t)
    if current:
        chunks.append("".join(current))
    long = [(i + 1, len(c)) for i, c in enumerate(chunks) if len(c) > 800]
    if long:
        raise SystemExit(f"Subsection over 800 chars: {long}")


